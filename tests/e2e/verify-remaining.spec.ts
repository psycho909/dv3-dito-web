import { expect, test } from '@playwright/test'

test('核對剩餘數時拒絕無效值並可在記錄已知遺漏點數後恢復同步', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '確認從 52 顆開始記錄' }).click()
  for (const rank of ['4', '7', '6']) await page.locator(`[data-rank-key="${rank}"]`).click()

  await page.locator('.remaining-verification summary').click()
  const input = page.getByRole('textbox', { name: '遊戲畫面目前剩幾顆？' })
  await input.fill('48.5')
  await page.getByRole('button', { name: '核對' }).click()
  await expect(input).toBeFocused()
  await expect(input).toHaveValue('48.5')
  await expect(page.getByRole('alert')).toBeVisible()

  await input.fill('48')
  await page.getByRole('button', { name: '核對' }).click()
  await expect(page.getByRole('heading', { name: '目前不能保證精確機率' })).toBeVisible()
  await expect(page.getByRole('region', { name: '本局建議' })).toHaveCount(0)
  await expect(page.locator('[data-tier-probability]')).toHaveCount(0)
  await expect(page.getByRole('button', { name: '撤銷輸入' })).toBeVisible()
  await expect(page.locator('[data-rank-key="4"]')).toContainText('3')
  await page.reload()
  await expect(page.getByRole('heading', { name: '目前不能保證精確機率' })).toBeVisible()
  await expect(page.locator('[data-tier-probability]')).toHaveCount(0)

  await page.locator('[data-rank-key="2"]').click()
  await expect(page.getByRole('region', { name: '本局建議' })).toHaveCount(0)
  await page.locator('.remaining-verification summary').click()
  await page.getByRole('textbox', { name: '遊戲畫面目前剩幾顆？' }).fill('48')
  await page.getByRole('button', { name: '核對' }).click()
  await expect(page.getByText('牌池未同步')).toHaveCount(0)
  await expect(page.getByRole('region', { name: '本局建議' })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('region', { name: '本局建議' })).toBeVisible()
})

test('未開始記錄時不顯示核對入口；開始後鍵盤可開啟並送出核對', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByText('核對遊戲剩餘顆數')).toHaveCount(0)

  const start = page.getByRole('button', { name: '確認從 52 顆開始記錄' })
  await start.focus()
  await page.keyboard.press('Enter')
  const summary = page.locator('.remaining-verification summary')
  await summary.focus()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('textbox', { name: '遊戲畫面目前剩幾顆？' })).toBeVisible()
  const summaryBounds = await summary.boundingBox()
  expect(summaryBounds?.height).toBeGreaterThanOrEqual(44)
  await page.getByRole('textbox', { name: '遊戲畫面目前剩幾顆？' }).fill('52')
  await page.getByRole('textbox', { name: '遊戲畫面目前剩幾顆？' }).press('Enter')
  await expect(page.locator('.remaining-verification [role="status"]')).toHaveText('核對相符：遊戲與工具皆剩 52 顆。')
  await expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true)
})

test('核對後撤銷誤記，恢復機率與推薦', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '確認從 52 顆開始記錄' }).click()
  await page.locator('[data-rank-key="4"]').click()
  await page.locator('.remaining-verification summary').click()
  await page.getByRole('textbox', { name: '遊戲畫面目前剩幾顆？' }).fill('52')
  await page.getByRole('button', { name: '核對' }).click()
  await expect(page.getByRole('heading', { name: '目前不能保證精確機率' })).toBeVisible()
  await page.getByRole('button', { name: '撤銷輸入' }).click()
  await expect(page.getByRole('region', { name: '本局建議' })).toHaveCount(0)
  await page.getByRole('button', { name: '核對' }).click()
  await expect(page.getByRole('region', { name: '本局建議' })).toBeVisible()
  await expect(page.locator('[data-tier-probability]').first()).toBeVisible()
})
